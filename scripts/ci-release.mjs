import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const app=JSON.parse(fs.readFileSync('app.json','utf8')).expo;
const source='android/app/build/outputs/apk/release/app-release.apk';
const sdk=process.env.ANDROID_HOME;
const version=fs.readdirSync(path.join(sdk,'build-tools')).filter(v=>/^\d/.test(v)).sort((a,b)=>b.localeCompare(a,undefined,{numeric:true}))[0];
const tools=path.join(sdk,'build-tools',version);
const metadata=execFileSync(path.join(tools,'aapt'),['dump','badging',source],{encoding:'utf8'});
if(metadata.includes('application-debuggable')) throw Error('Debug APK rejected');
const identity=/package: name='([^']+)' versionCode='(\d+)' versionName='([^']+)'/.exec(metadata);
if(!identity || identity[1]!==app.android.package || Number(identity[2])!==app.android.versionCode || identity[3]!==app.version) throw Error('APK identity mismatch');
const signature=execFileSync(path.join(tools,'apksigner'),['verify','--print-certs',source],{encoding:'utf8'});
const cert=/certificate SHA-256 digest:\s*([a-f0-9]{64})/i.exec(signature)?.[1];
if(!cert) throw Error('Invalid APK signature');
const bytes=fs.readFileSync(source), sha256=createHash('sha256').update(bytes).digest('hex');
const name=`inteliagent-${app.android.versionCode}-${sha256.slice(0,12)}.apk`;
fs.mkdirSync('release',{recursive:true}); fs.copyFileSync(source,'release/'+name);
fs.writeFileSync('release/latest.json',JSON.stringify({packageName:app.android.package,version:app.version,versionCode:app.android.versionCode,sha256,size:bytes.length,certificateSha256:cert,downloadUrl:`https://github.com/${process.env.GITHUB_REPOSITORY}/releases/download/v${app.version}+build.${app.android.versionCode}/${name}`,publishedAt:new Date().toISOString(),notes:process.env.RELEASE_NOTES||'Atualização publicada pelo CI/CD.'},null,2)+'\n');
fs.writeFileSync('release/SHA256SUMS',`${sha256}  ${name}\n`);
